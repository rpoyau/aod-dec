"""Translate a bounded exact cell-transport fixture into scalar Dec core v1.

The generator unrolls a declared schedule. It adds no array, cell, or loop syntax
to the compiler and does not replace the independent pair-transfer simulator.
All next-state values use the old state, then commit together at each Euler step.
"""
from __future__ import annotations

from fractions import Fraction

from .cell_transport import ModelConfig, make_schedule, transition_kernel, validate_schedule


VARIABLES = ("emitter", *(f"cell_{i}" for i in range(8)), "output", "loss")
EMIT_VARIABLES = (*VARIABLES, "injected")
MAX_EXPANDED_STEPS = 128


def _literal(value: Fraction | int) -> str:
    value = Fraction(value)
    return f"ratio({value.numerator}, {value.denominator})"


def _weighted_sum(coefficients, names):
    terms = []
    for coefficient, name in zip(coefficients, names):
        if coefficient == 1:
            terms.append(name)
        elif coefficient != 0:
            terms.append(f"{name} * {_literal(coefficient)}")
    return " + ".join(terms) if terms else _literal(0)


def dec_source(config=ModelConfig(), substeps=1, schedule=None) -> str:
    """Return a complete Dec program emitting twelve final exact values then 0.

    Output order matches ``cell_transport.flatten_state``: emitter, eight cells
    in FACETS order, output, loss, injected. A maximum of 128 expanded steps keeps
    this scalar demonstration bounded; finer reference studies use the Python
    model and are not silently represented by a shorter Dec run.
    """
    if not isinstance(config, ModelConfig):
        raise TypeError("config must be ModelConfig")
    if type(substeps) is not int or substeps <= 0:
        raise ValueError("substeps must be a positive integer")
    if config.intervals * substeps > MAX_EXPANDED_STEPS:
        raise ValueError("scalar Dec fixture exceeds 128 expanded steps")
    schedule = make_schedule(config.intervals) if schedule is None else schedule
    validate_schedule(config, schedule)
    h = Fraction(1, substeps)
    initial = (config.initial_emitter, *config.initial_cells, Fraction(0), Fraction(0))
    initial_total = sum(initial)
    pump = h * config.pump
    body = [f"ratio {name} = {_literal(value)}" for name, value in zip(VARIABLES, initial)]
    body.append(f"ratio injected = {_literal(0)}")
    body.extend(f"ratio next_{name} = {_literal(0)}" for name in VARIABLES)
    for macro in range(config.intervals):
        kernel = transition_kernel(config, schedule["multipliers"][macro], h)
        for local in range(substeps):
            body.append(f"# Interval {macro}, substep {local}: all expressions read old values.")
            for destination, name in enumerate(VARIABLES):
                expression = _weighted_sum(
                    (row[destination] for row in kernel), VARIABLES,
                )
                if destination == 0 and pump:
                    expression += f" + {_literal(pump)}"
                body.append(f"next_{name} = {expression}")
            body.extend(f"{name} = next_{name}" for name in VARIABLES)
            body.append(f"injected = injected + {_literal(pump)}")
            body.append(f"assert {' + '.join(VARIABLES)} == {_literal(initial_total)} + injected")
    body.extend(f"emit {name}" for name in EMIT_VARIABLES)
    body.append("result = 0")
    return ("# Generated by simulations/transport_dec.py; declared exact cell-transport fixture.\n"
            f"# Retained jitter schedule SHA-256: {schedule['sha256']}\n"
            "Dec main() -> result:\n"
            "    () -> int result:\n" + "".join(f"        {line}\n" for line in body))
